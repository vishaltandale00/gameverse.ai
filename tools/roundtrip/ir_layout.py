"""Artifact-only placement for bounded IR replacements in retained ROM hosts."""
from __future__ import annotations

import copy
import json
from pathlib import Path

from .native_provider import assemble_native_layout
from .reassemble import assemble, sha


def build_layout(original_path, baseline_path, output, replacements, appended_bytes=b""):
    """Retain source pins separately from generated output placement identities.

    Replacements are (original offset, generated bytes, identity, stratum).
    The original is consulted only to authenticate the captured baseline; the
    actual reconstruction consumes the isolated output artifact files.
    """
    original_path, baseline_path, output = map(Path, (original_path, baseline_path, output))
    base = json.loads(baseline_path.read_text())
    captured, _ = assemble(baseline_path)
    raw = original_path.read_bytes()
    if captured != raw or sha(raw) != base["original"]["sha256"]:
        raise ValueError("Captured baseline does not exactly reconstruct pinned original")
    replacements = sorted(replacements)
    cursor = 0
    for offset, data, identity, _ in replacements:
        if not data or offset < cursor or offset + len(data) > len(raw):
            raise ValueError("Invalid, overlapping or out-of-bounds IR replacement: " + identity)
        cursor = offset + len(data)
    (output / "source-components").mkdir()
    (output / "output-components").mkdir()
    # Preserve the baseline's referenced attribution evidence under the same
    # relative names so the new standalone manifest has no dangling receipts.
    evidence_refs = {ref["path"]: ref for row in base["components"]
                     for ref in row.get("evidence", []) if "path" in ref}
    for name, ref in evidence_refs.items():
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("Baseline evidence must be local to its packet")
        evidence = (baseline_path.parent / relative).read_bytes()
        if sha(evidence) != ref["sha256"]:
            raise ValueError("Stale baseline attribution evidence")
        destination = output / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(evidence)
    cuts = {x for offset, data, *_ in replacements for x in (offset, offset + len(data))}
    sources, placements = [], []
    producer_evidence = [{"path": str(path.relative_to(output)), "sha256": sha(path.read_bytes())}
                         for path in sorted(output.rglob("*"))
                         if path.is_file() and (path.name in ("native.bin", "native.elf", "l1.json", "generated.c", "original-proof.json"))]
    if not producer_evidence:
        raise ValueError("Actual IR producer artifacts required for generated placements")

    def save(directory, identity, data):
        path = directory + "/" + identity + ".bin"
        (output / path).write_bytes(data)
        return {"path": path, "sha256": sha(data)}

    for row in base["components"]:
        start, end = row["offset"], row["offset"] + row["size"]
        bounds = sorted({start, end} | {x for x in cuts if start < x < end})
        for lo, hi in zip(bounds, bounds[1:]):
            source = copy.deepcopy(row)
            identity = row["id"] if (lo, hi) == (start, end) else row["id"] + f".slice{lo:x}"
            data = captured[lo:hi]
            source.update(id=identity, offset=lo, size=hi-lo, sha256=sha(data), version="sha256:" + sha(data))
            source["artifact"] = save("source-components", identity, data)
            if (lo, hi) != (start, end):
                source.update(dependencies=[], evidence=copy.deepcopy(row.get("evidence", [])),
                              closure={"status": "unknown", "reason": "Partial source ownership span; original dependency semantics remain open"})
            sources.append(source)
            replacement = next((r for r in replacements if r[0] <= lo and hi <= r[0]+len(r[1])), None)
            right = replacement[1][lo-replacement[0]:hi-replacement[0]] if replacement else data
            placements.append({"id": identity, "sourceComponent": identity, "version": source["version"],
                               "offset": lo, "size": hi-lo, "sha256": sha(right),
                               "artifact": save("output-components", identity, right),
                               "stratum": replacement[3] if replacement else source["stratum"],
                               "providerKind": "ir_generated" if replacement else source["provider"]["kind"],
                               "transform": "ir-entry-replacement" if replacement else "identity-placement",
                               "evidence": producer_evidence if replacement else copy.deepcopy(source.get("evidence", []))})
    if appended_bytes:
        identity = "ir-generated-payload"
        placements.append({"id": identity, "sourceComponent": None, "role": "generated-output",
                           "version": "sha256:" + sha(appended_bytes), "offset": len(raw),
                           "size": len(appended_bytes), "sha256": sha(appended_bytes),
                           "artifact": save("output-components", identity, appended_bytes),
                           "stratum": "ir-regenerated", "providerKind": "ir_generated", "evidence": producer_evidence})
    # Dependencies into an ownership span which was split cannot retain the old
    # identity as resolved. Keep the missing semantic boundary visible.
    ids = {row["id"] for row in sources}
    for row in sources:
        for edge in row.get("dependencies", []):
            if edge.get("target") not in ids:
                edge.update(status="unknown", reason="Dependency ownership span split for IR placement")
    manifest = copy.deepcopy(base)
    manifest.update(components=sources, prefabs=[], claims={"container_exact_reconstruction": False,
                    "whole_game_semantic_closure": False})
    rebuilt = b"".join((output / row["artifact"]["path"]).read_bytes()
                       for row in sorted(placements, key=lambda r: r["offset"]))
    layout = {"schema": "gameverse.rom-roundtrip-layout/1", "originalSha256": sha(raw),
              "artifact": {"sha256": sha(rebuilt), "size": len(rebuilt),"path":str((output/"rebuilt.gba").resolve())},
              "components": placements, "reconstruction_mode": "native-relocated"}
    for name, value in (("manifest.json", manifest), ("layout.json", layout)):
        (output / name).write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")
    layout = assemble_native_layout(output / "layout.json", output / "rebuilt.gba")
    return rebuilt, layout, manifest
