def emit(source: Path, output: Path) -> dict:
    """Extract native permutation table and fail closed on changed source ABI."""
    for name, expected in SOURCE_HASHES.items():
        if hashlib.sha256((source/name).read_bytes()).hexdigest() != expected:
            raise ValueError(f'unsupported source revision: {name}')
    pokemon = (source/'src/pokemon.c').read_text()
    header = (source/'include/pokemon.h').read_text()
    rows = re.findall(r'SUBSTRUCT_CASE\(\s*(\d+),\s*(\d),\s*(\d),\s*(\d),\s*(\d)\)', pokemon)
    if len(rows) != 24 or [int(r[0]) for r in rows] != list(range(24)):
        raise ValueError('unsupported native permutation table')
    for row in rows:
        if sorted(map(int,row[1:])) != [0,1,2,3]: raise ValueError('invalid permutation')
    # Exact immutable source hashes are recorded; explicit structure assertions in
    # fixture compilation below establish byte offsets independently of this code.
    for token in ('u16 species;', 'u16 heldItem;', 'u16 moves[MAX_MON_MOVES];', 'u16 checksum;', 'u16 unknown;'):
        if token not in header: raise ValueError('unsupported native BoxPokemon ABI')
    table = ','.join('{'+','.join(r[1:])+'}' for r in rows)
    output.mkdir(parents=True,exist_ok=True)
    (output/'wg_box_codec.h').write_text(HEADER)
    (output/'wg_box_codec.c').write_text(C_TEMPLATE.replace('{TABLE}','{'+table+'}'))
    files = ['src/pokemon.c','include/pokemon.h','include/constants/species.h','include/constants/moves.h','include/constants/items.h']
    capsule = {'schemaVersion':1,'codecVersion':1,'sourceCommit':SOURCE_COMMIT,
        'sourceFiles':{p:hashlib.sha256((source/p).read_bytes()).hexdigest() for p in files},
        'nativeBytesPerSlot':80,'packedBytesPerSlot':75,'slots':420,'guaranteedBytesSaved':2100,
        'supportedDomain':{'speciesExclusive':413,'heldItemExclusive':377,'moveExclusive':355},
        'layout':{'header':[0,32],'growthTail':[32,40],'attackTailAndOtherCore':[40,68],'sixLittleEndian9BitIds':[68,75]},
        'preserved':'All 80 native bytes reconstructed exactly; header flags, padding, filler and original checksum retained.',
        'failurePolicy':'Any invalid ID, native checksum or packed padding rejects entire slot array before destination mutation; caller must reject save before flash writes.',
        'scope':'Codec prerequisite only; does not certify whole-game save capacity, persistence or crash recovery.'}
    (output/'capsule.json').write_text(json.dumps(capsule,indent=2)+'\n')
    return capsule

